"""Error mapping for tool calls (DECISIONS D20).

Anything that is not a genuine upstream `CallToolResult` becomes a fixed message the agent sees.
Exception messages, arguments and tracebacks never reach the agent, the logs or the audit log:
only exception type names and fixed fields do.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import StrEnum
from typing import Any

import anyio
import httpx2
from mcp.shared.exceptions import MCPError
from mcp.types import CallToolResult, TextContent
from mcp_types.jsonrpc import CONNECTION_CLOSED, REQUEST_TIMEOUT


class Outcome(StrEnum):
    OK = "ok"
    TOOL_ERROR = "tool_error"
    PROTOCOL_ERROR = "protocol_error"
    TIMEOUT = "timeout"
    UNAVAILABLE = "unavailable"
    UNKNOWN_TOOL = "unknown_tool"
    AUDIT_UNAVAILABLE = "audit_unavailable"
    INTERNAL_ERROR = "internal_error"


# Whether the gateway knows if the upstream executed the call. After a timeout or a broken
# connection the upstream may or may not have run it (THREAT_MODEL: retries can duplicate effects).
OUTCOME_KNOWN = {
    Outcome.OK: True,
    Outcome.TOOL_ERROR: True,
    Outcome.PROTOCOL_ERROR: True,
    Outcome.TIMEOUT: False,
    Outcome.UNAVAILABLE: False,
    Outcome.UNKNOWN_TOOL: True,  # never forwarded
    Outcome.AUDIT_UNAVAILABLE: True,  # never forwarded
    Outcome.INTERNAL_ERROR: False,
}

AGENT_TEXT = {
    Outcome.TIMEOUT: "TaintwallError: upstream timed out",
    Outcome.UNAVAILABLE: "TaintwallError: upstream unavailable",
    Outcome.UNKNOWN_TOOL: "TaintwallError: unknown tool",
    Outcome.AUDIT_UNAVAILABLE: "TaintwallError: audit unavailable, call not forwarded",
    Outcome.INTERNAL_ERROR: "TaintwallError: internal error",
}

# Raised by the network or stream layer when an upstream connection fails or breaks.
TRANSPORT_ERRORS: tuple[type[BaseException], ...] = (
    httpx2.HTTPError,
    OSError,
    anyio.BrokenResourceError,
    anyio.ClosedResourceError,
    anyio.EndOfStream,
)


@dataclass(frozen=True)
class MappedError:
    outcome: Outcome
    agent_text: str
    log_fields: dict[str, Any] = field(default_factory=dict)

    def result(self) -> CallToolResult:
        return error_result(self.agent_text)


def error_result(text: str) -> CallToolResult:
    return CallToolResult(content=[TextContent(text=text)], is_error=True)


def leaf_exceptions(exc: BaseException) -> list[BaseException]:
    """Flatten (possibly nested) exception groups into their leaf exceptions."""
    if isinstance(exc, BaseExceptionGroup):
        return [leaf for inner in exc.exceptions for leaf in leaf_exceptions(inner)]
    return [exc]


def map_upstream_exception(exc: Exception) -> MappedError:
    """Map an exception raised while calling an upstream to what the agent and the logs see."""
    leaves = leaf_exceptions(exc)
    types = [type(leaf).__name__ for leaf in leaves]
    if len(leaves) == 1:
        leaf = leaves[0]
        if isinstance(leaf, TimeoutError):
            return MappedError(Outcome.TIMEOUT, AGENT_TEXT[Outcome.TIMEOUT], {"exc_types": types})
        if isinstance(leaf, MCPError):
            code = int(leaf.error.code)
            if code == CONNECTION_CLOSED:
                # Generated by the SDK client when the transport fails (client/streamable_http.py).
                return MappedError(
                    Outcome.UNAVAILABLE,
                    AGENT_TEXT[Outcome.UNAVAILABLE],
                    {"exc_types": types, "code": code},
                )
            if code == REQUEST_TIMEOUT:
                return MappedError(
                    Outcome.TIMEOUT, AGENT_TEXT[Outcome.TIMEOUT], {"exc_types": types, "code": code}
                )
            return MappedError(
                Outcome.PROTOCOL_ERROR,
                f"TaintwallError: upstream error (code {code})",
                {"exc_types": types, "code": code},
            )
    if all(isinstance(leaf, TRANSPORT_ERRORS) for leaf in leaves):
        return MappedError(
            Outcome.UNAVAILABLE, AGENT_TEXT[Outcome.UNAVAILABLE], {"exc_types": types}
        )
    return MappedError(
        Outcome.INTERNAL_ERROR, AGENT_TEXT[Outcome.INTERNAL_ERROR], {"exc_types": types}
    )
